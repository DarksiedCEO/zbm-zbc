"""
Environment configuration (Legal spec §E, §H). Every rule fails closed: a configuration the service cannot
honor refuses start-up with a plain message. Options that would need something this build does not have (a
counsel channel, an e-sign provider, portal FAQ answers) refuse to start rather than pretend.

Seed pinning (spec §B.12, G4): every file in ``seed/`` is pinned by SHA-256 here and in ADR 0010. The rules
seed alone may run unpinned for a NON-PRODUCTION run (``LEGAL_ALLOW_UNPINNED_SEED=1`` with its own hash stated
in ``LEGAL_SEED_SHA256``; /health then says ``rules_pinned: false``) — the N14-13 override. Any other seed
file that differs refuses start-up with no override.
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass, field
from decimal import Decimal
from typing import Optional

# Callers whose token is set on a service deployed in the same apply as Legal's new caller map (ADR 0028 AEGIS M-1).
# An empty or unresolved entry for one of them is SKIPPED (no token matches it; routes only it may call answer 503,
# /health warns ``optional_caller_unset:<name>`` and the start prints a warning) instead of refusing Legal's start. A
# set value is checked like every other caller token. Every other caller stays strict. ``compliance_38`` (ADR 0024):
# on the first apply COMPLIANCE_LEGAL_CALLER_TOKEN does not exist yet; ``client_portal`` (ADR 0028): the same for
# PORTAL_LEGAL_CALLER_TOKEN.
OPTIONAL_CALLERS = ("compliance_38", "client_portal")
CALLER_NAMES = ("compliance_38", "clipper_network", "verification_integrity", "creative_production", "onboarding",
                "finance_31", "hub", "esign_gateway", "scheduler", "client_portal")
# ADR 0028: ZBM's own entity facts a client template names as ``{{zbm_*}}`` variables (legal entity name, entity type and
# state, street address, ...). Filled from LEGAL_ZBM_FACTS at fill time, never from a request, never hard-coded.
ZBM_FACT_NAME = re.compile(r"^zbm_[a-z0-9_]{1,36}$")
ZBM_FACT_MAX = 500
TOKEN_MIN = 32
# AEGIS night review M-2: a Railway variable reference that was not resolved reaches the service as its literal text.
# "${{LEGAL_ONBOARDING_CALLER_TOKEN}}" is >= 32 printable characters and is public in the repo (.railway/railway.ts),
# so it passed the length check. Any token value holding a template marker is refused at start-up.
UNRESOLVED_REF_MARKERS = ("${{", "{{")
SEED_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "seed")
RULES_SEED = "legal_rules_seed.json"
# SHA-256 of each seed file as generated by devtools/gen_seeds.py (pinned in ADR 0010).
PINNED_SEEDS = {
    "legal_rules_seed.json": "140a118216b8c0d1a3baee93daa261affe3058733cb9f97fe1f8c0bf99735ff4",
    "documents.json": "2073717e838b2ddec39027d8c4b68ed91ebdc1df683621faef72dc199939afbe",
    "counsel_questions.json": "8a00b2912611547fe7d38c3f9d3794824df804168aa2673cd1532cb666da2778",
    "retention.json": "712efb7a7ed72bdd5896c47f51f9f1cd9fcc7503383ced80568b1385d80ae286",
    "signoff_topics.json": "3651fc599248be8656e83fcffc9c5b66d48a0d9712437c316f6678c95a9ab590",
    "advice_patterns.json": "cf43405ee79ac0779ac466605b31e7ea6e61fa9ba9a7af1ca3e7a440a1719be3",
    "us_federal_holidays.json": "54cf0db79fa3c4f9eb452797681d8c7114bd57aa43557896a76eaaada8b1b1f5",
}
PINNED_SEED_SHA256 = PINNED_SEEDS[RULES_SEED]
_MONEY = re.compile(r"^(0|[1-9][0-9]*)\.[0-9]{2}$")


@dataclass
class Settings:
    service_token: str
    caller_tokens: dict = field(default_factory=dict)
    callers_not_configured: tuple = ()                            # optional callers left empty or unresolved
    andre_token: Optional[str] = None
    seed_dir: str = SEED_DIR
    seed_sha256: Optional[str] = None
    allow_unpinned_seed: bool = False
    data_dir: Optional[str] = None
    ledger_url: Optional[str] = None
    ledger_token: Optional[str] = None
    reconcile_mode: bool = False
    compliance_url: Optional[str] = None
    compliance_token: Optional[str] = None
    compliance_caller_token: Optional[str] = None
    agent_max_fallback: int = 1
    dispute_threshold: Decimal = Decimal("5000.00")
    memo_review_days: int = 90
    hold_renotice_days: int = 90
    filing_alert_days: int = 60
    esign_consent_required: bool = True
    business_tz: str = "America/Los_Angeles"
    zbm_facts: dict = field(default_factory=dict)                 # ADR 0028: {{zbm_*}} values (LEGAL_ZBM_FACTS)
    link_tag_key: Optional[bytes] = field(default=None, repr=False)   # AEGIS r2 N-M1 (LEGAL_LINK_TAG_KEY)
    link_tag_problem: Optional[str] = None                        # AEGIS r3 N3-L4: why links are off
    data_dir_lock: Optional[object] = field(default=None, repr=False, compare=False)   # bug sweep E: the flock


_HELD: dict = {}


def hold_data_dir(data_dir: str):
    """Bug sweep E (E-5/F-3; service-py's): the exclusive flock on LEGAL_DATA_DIR, taken once per process at start-up
    before the log is opened, held for the life of the process (the kernel releases it at exit). A second process on
    the same directory refuses to start; a second service instance in the same process must ``claim()`` it and is
    refused while one holds it."""
    from store import LOCK_NAME, DataDirBusy, DataDirLock, StoreCorrupt
    key = os.path.realpath(data_dir)
    lock = _HELD.get(key)
    if lock is None:
        try:
            lock = DataDirLock(data_dir)
        except DataDirBusy:
            raise RuntimeError(f"{data_dir}: another legal-py process holds this data directory (flock on "
                               f"{LOCK_NAME}); refusing to start. Stop the other process first: two writers would "
                               "fork the log") from None
        except StoreCorrupt as exc:
            raise RuntimeError(f"{data_dir}: {exc}") from None
        _HELD[key] = lock
    return lock


def _int(env, name, default, lo, hi) -> int:
    raw = env.get(name)
    if raw in (None, ""):
        return default
    try:
        v = int(raw)
    except ValueError:
        v = lo - 1
    if not lo <= v <= hi:
        raise RuntimeError(f"{name} must be an integer {lo}..{hi}")
    return v


def _flag(env, name, default: bool) -> bool:
    raw = (env.get(name) or "").strip()
    if raw == "":
        return default
    if raw not in ("0", "1"):
        raise RuntimeError(f"{name} must be 0 or 1")
    return raw == "1"


def _check_ref(value: Optional[str], what: str) -> None:
    """Refuse a token setting whose value is an unresolved Railway reference (``${{X}}`` or ``{{X}}``) left as literal
    text. Names the setting only: the value never appears in the message."""
    if value and any(m in value for m in UNRESOLVED_REF_MARKERS):
        raise RuntimeError(f"{what} holds an unresolved Railway reference (a '${{{{...}}}}' placeholder), not a token: "
                           "set the referenced variable in Railway, then redeploy; refusing to start")


def _check_token(value: str, what: str) -> None:
    """The check for every caller token this service ACCEPTS: not an unresolved reference, then >= TOKEN_MIN printable
    ASCII characters."""
    _check_ref(value, what)
    if len(value) < TOKEN_MIN or not all(0x21 <= ord(c) <= 0x7e for c in value):
        raise RuntimeError(f"{what} must be >= {TOKEN_MIN} printable ASCII characters")


def _optional_unset(name: str, tok: str) -> bool:
    return name in OPTIONAL_CALLERS and (tok.strip() == "" or any(m in tok for m in UNRESOLVED_REF_MARKERS))


def _not_configured(env, name) -> tuple:
    raw = env.get(name)
    try:
        d = json.loads(raw) if raw else {}
    except ValueError:
        d = {}
    d = d if isinstance(d, dict) else {}
    return tuple(c for c in OPTIONAL_CALLERS if not isinstance(d.get(c), str) or _optional_unset(c, d[c]))


def _tokens(env, name) -> dict:
    raw = env.get(name)
    if not raw:
        return {}
    try:
        d = json.loads(raw)
    except ValueError:
        d = None
    if not isinstance(d, dict) or not all(isinstance(k, str) and isinstance(v, str) for k, v in d.items()):
        raise RuntimeError(f'{name} must be a JSON object {{"name": "token", ...}}')
    for k, tok in d.items():
        if k not in CALLER_NAMES:
            raise RuntimeError(f"{name}: unknown name (allowed: {', '.join(CALLER_NAMES)})")
        if _optional_unset(k, tok):
            continue
        _check_token(tok, f"{name}: the {k} token")
    return {k: v for k, v in d.items() if not _optional_unset(k, v)}


def _off(env, name, what: str) -> None:
    raw = (env.get(name) or "").strip().lower()
    if raw not in ("", "none", "0"):
        raise RuntimeError(f"{name}={raw!r}: {what} is not built in this service; leave it unset (the fail-closed "
                           "stand-in answers 'not delivered' / 'unavailable')")


def _zbm_facts(env: dict) -> dict:
    """ADR 0028: LEGAL_ZBM_FACTS, a JSON object of ``zbm_*`` names to non-empty printable strings (no ``{{``/``}}``,
    at most 500 characters). Unset = no facts (a fill of a template that names one is refused, never guessed)."""
    raw = env.get("LEGAL_ZBM_FACTS")
    if raw is None or raw.strip() == "":
        return {}
    try:
        data = json.loads(raw)
    except ValueError:
        raise RuntimeError("LEGAL_ZBM_FACTS must be a JSON object {\"zbm_legal_entity_name\": \"...\", ...}") from None
    if not isinstance(data, dict):
        raise RuntimeError("LEGAL_ZBM_FACTS must be a JSON object {\"zbm_legal_entity_name\": \"...\", ...}")
    for k, v in data.items():
        if not isinstance(k, str) or not ZBM_FACT_NAME.fullmatch(k):
            raise RuntimeError("LEGAL_ZBM_FACTS: every name is zbm_[a-z0-9_]{1,36}")
        if (not isinstance(v, str) or not v.strip() or len(v) > ZBM_FACT_MAX or "{{" in v or "}}" in v
                or re.search(r"[\x00-\x1f\x7f-\x9f]", v)):
            raise RuntimeError(f"LEGAL_ZBM_FACTS: {k} must be 1-{ZBM_FACT_MAX} printable characters with no {{{{ }}}}")
    return dict(data)


def _link_tag_key(env: dict, others: list) -> tuple:
    """AEGIS r2 N-M1: the key that tags client acceptance link tokens, the same value as the client-portal service's
    PORTAL_LINK_TAG_KEY. AEGIS r3 N3-L4: unset or malformed (an unresolved reference, under 32 printable characters,
    a space) never stops Legal: link issuance and the portal routes answer 503 with the reason, /health says it.
    AEGIS r3 N3-L1: a key equal to any other secret Legal holds refuses the start (a founder-grade secret must never
    reach the public-facing service's environment). Returns (key or None, the reason links are off or None)."""
    raw = env.get("LEGAL_LINK_TAG_KEY")
    if raw is None or raw == "":
        return None, "off: LEGAL_LINK_TAG_KEY is not set"
    if any(raw == o for o in others if o):
        raise RuntimeError("LEGAL_LINK_TAG_KEY equals another secret this service holds (a service, Andre, caller, "
                           "ledger or Compliance token): set its own value (openssl rand -hex 32); refusing to start")
    try:
        _check_token(raw, "LEGAL_LINK_TAG_KEY")
    except RuntimeError as exc:
        return None, f"off: {exc}".replace("; refusing to start", "")
    return raw.encode("ascii"), None


def load(env: Optional[dict] = None) -> Settings:
    env = dict(os.environ) if env is None else env
    token = env.get("LEGAL_SERVICE_TOKEN")
    if not token:
        raise RuntimeError("LEGAL_SERVICE_TOKEN is not set. legal-py refuses to start without an auth token "
                           "(fail closed, not open).")
    andre = env.get("LEGAL_ANDRE_APPROVAL_TOKEN") or None
    # the service and Andre tokens carry no length rule here (unchanged); the unresolved-reference refusal applies to
    # them, to the caller map and to the outbound ledger and Compliance tokens alike
    _check_ref(token, "LEGAL_SERVICE_TOKEN")
    _check_ref(andre, "LEGAL_ANDRE_APPROVAL_TOKEN")
    callers = _tokens(env, "LEGAL_CALLER_TOKENS")
    every = list(callers.values())
    if len(set(every)) != len(every):
        raise RuntimeError("LEGAL_CALLER_TOKENS: every token must be distinct")
    if token in every or (andre and andre in every):
        raise RuntimeError("a caller token equals the service or Andre token")
    _off(env, "LEGAL_COUNSEL_CHANNEL", "a counsel channel (spec D1: engagement letter TBD)")
    _off(env, "LEGAL_ESIGN_PROVIDER", "an e-sign provider (spec D2, LR decision 7)")
    if _flag(env, "LEGAL_PORTAL_FAQ", False):
        raise RuntimeError("LEGAL_PORTAL_FAQ=1: portal FAQ answers are not built (spec D5, CQ-15: route only); "
                           "refusing to start")
    unpinned = _flag(env, "LEGAL_ALLOW_UNPINNED_SEED", False)
    seed_sha = env.get("LEGAL_SEED_SHA256") or None
    if seed_sha is not None and seed_sha != PINNED_SEED_SHA256 and not unpinned:
        raise RuntimeError("LEGAL_SEED_SHA256 differs from the pinned rules seed hash; refusing to start "
                           "(set LEGAL_ALLOW_UNPINNED_SEED=1 for a NON-PRODUCTION run)")
    if unpinned and seed_sha is None:
        raise RuntimeError("LEGAL_ALLOW_UNPINNED_SEED=1 needs LEGAL_SEED_SHA256 (the unpinned seed's own hash, stated)")
    comp = [env.get(k) or None for k in ("LEGAL_COMPLIANCE_URL", "LEGAL_COMPLIANCE_TOKEN",
                                         "LEGAL_COMPLIANCE_CALLER_TOKEN")]
    _check_ref(comp[1], "LEGAL_COMPLIANCE_TOKEN")                 # outbound: what this service SENDS Compliance
    _check_ref(comp[2], "LEGAL_COMPLIANCE_CALLER_TOKEN")
    _check_ref(env.get("LEDGER_SERVICE_TOKEN"), "LEDGER_SERVICE_TOKEN")   # outbound, to the evidence ledger
    if any(comp) and not all(comp):
        raise RuntimeError("LEGAL_COMPLIANCE_URL, LEGAL_COMPLIANCE_TOKEN and LEGAL_COMPLIANCE_CALLER_TOKEN must be "
                           "set together (or none: the fail-closed Compliance stand-in)")
    raw_thr = (env.get("LEGAL_DISPUTE_THRESHOLD") or "5000.00").strip()
    if not _MONEY.fullmatch(raw_thr) or Decimal(raw_thr) <= 0:
        raise RuntimeError('LEGAL_DISPUTE_THRESHOLD must be a positive money string like "5000.00"')
    tz = (env.get("LEGAL_BUSINESS_TZ") or "America/Los_Angeles").strip()
    try:
        from zoneinfo import ZoneInfo
        ZoneInfo(tz)
    except Exception:  # noqa: BLE001 - any failure: refuse (no silent UTC fallback)
        raise RuntimeError(f"LEGAL_BUSINESS_TZ={tz!r} is not a known IANA time zone on this host") from None
    s = Settings(
        service_token=token, caller_tokens=callers, andre_token=andre,
        callers_not_configured=_not_configured(env, "LEGAL_CALLER_TOKENS"),
        seed_dir=env.get("LEGAL_SEED_DIR") or SEED_DIR, seed_sha256=seed_sha, allow_unpinned_seed=unpinned,
        data_dir=env.get("LEGAL_DATA_DIR") or None,
        ledger_url=env.get("LEDGER_SERVICE_URL") or None, ledger_token=env.get("LEDGER_SERVICE_TOKEN") or None,
        reconcile_mode=_flag(env, "LEGAL_RECONCILE_MODE", False),
        compliance_url=comp[0], compliance_token=comp[1], compliance_caller_token=comp[2],
        agent_max_fallback=_int(env, "LEGAL_AGENT_MAX_FALLBACK", 1, 0, 1),
        dispute_threshold=Decimal(raw_thr),
        memo_review_days=_int(env, "LEGAL_MEMO_REVIEW_DAYS", 90, 1, 90),
        hold_renotice_days=_int(env, "LEGAL_HOLD_RENOTICE_DAYS", 90, 1, 90),
        filing_alert_days=_int(env, "LEGAL_FILING_ALERT_DAYS", 60, 1, 365),
        esign_consent_required=_flag(env, "LEGAL_ESIGN_CONSENT_REQUIRED", True),
        business_tz=tz,
        zbm_facts=_zbm_facts(env),
    )
    s.link_tag_key, s.link_tag_problem = _link_tag_key(
        env, [token, andre, env.get("LEDGER_SERVICE_TOKEN"), comp[1], comp[2], *callers.values(),
              *(v for v in (json.loads(env.get("LEGAL_CALLER_TOKENS") or "{}") or {}).values() if isinstance(v, str))])
    s.data_dir_lock = hold_data_dir(s.data_dir) if s.data_dir else None    # last: nothing above can fail after it
    return s


def read_seeds(settings: Settings) -> dict[str, bytes]:
    """Every seed file's bytes, checked against its pin (the rules seed against the stated override)."""
    out = {}
    for name, pin in PINNED_SEEDS.items():
        path = os.path.join(settings.seed_dir, name)
        with open(path, "rb") as fh:
            out[name] = fh.read()
        import hashlib
        got = hashlib.sha256(out[name]).hexdigest()
        if name == RULES_SEED:
            want = settings.seed_sha256 if (settings.allow_unpinned_seed and settings.seed_sha256) else pin
        else:
            want = pin
        if got != want:
            raise RuntimeError(f"seed {name} SHA-256 {got} does not match the expected {want}; refusing to start "
                               "(the seed must be the generated file, unchanged)")
    return out
