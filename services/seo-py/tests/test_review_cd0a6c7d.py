def test_the_script_fold_removes_an_accent_and_nothing_else_from_a_letter():
    """Over every letter of the Basic and Supplementary Multilingual Planes: the fold keeps the base letter, removes
    only marks of an accent class, and keeps every fixed-position mark (the kana voicing marks, the nukta)."""
    changed = collections.Counter()
    for o in range(0x80, 0x20000):
        c = chr(o)
        if not c.isalpha() or sg.normalise(c) != c or c == TATWEEL:    # (the tatweel: a letter that spells nothing)
            continue
        cf = unicodedata.normalize("NFD", c.casefold())
        got = unicodedata.normalize("NFD", sg._script_fold(c))
        marks = [m for m in cf if unicodedata.combining(m)]
        kept = [m for m in got if unicodedata.combining(m)]
        assert [m for m in cf if not unicodedata.combining(m)] == [m for m in got if not unicodedata.combining(m)], hex(o)
        assert kept == [m for m in marks if unicodedata.combining(m) < sg.ACCENT_CLASS_MIN], hex(o)
        if len(kept) != len(marks):
            changed[unicodedata.name(c).split(" ")[0]] += 1
    # the scripts of the label lists: the accent is dropped from Greek, Cyrillic and Arabic letters only
    assert changed["GREEK"] > 200 and changed["CYRILLIC"] > 40 and 1 <= changed["ARABIC"] <= 8
    assert not {"HIRAGANA", "KATAKANA", "DEVANAGARI", "THAI", "HANGUL", "HEBREW", "CJK"} & set(changed)
    blocks = ((0x3041, 0x30ff, 1), (0x900, 0x97f, 1), (0xe00, 0xe7f, 1), (0xac00, 0xd7a3, 97), (0x4e00, 0x9ffe, 211),
              (0x5d0, 0x5ea, 1))                               # kana, Devanagari, Thai, Hangul, Han, Hebrew
    for first, last, step in blocks:
        for o in range(first, last + 1, step):
            c = chr(o)
            if c.isalpha() and sg.normalise(c) == c:
                assert sg._script_fold(c) == c and sg._script_letters(c) == c and sg._cv_script_view(c) == c, hex(o)
    assert sg.ACCENT_CLASS_MIN == 200 and unicodedata.combining("\u3099") == unicodedata.combining("\u309a") == 8
    assert sg._script_fold("\u03cc") == "\u03bf" and sg._script_fold("\u03c2") == sg._script_fold("\u03a3") == "\u03c3"
    assert sg._script_fold(TATWEEL) == "" and sg._script_fold("\u093e") == "" and sg._script_fold("\u0130") == "i"
    # the client view's script view is the same fold, written in the character's own case
    capitals = chr(0x39a) + chr(0x38c) + chr(0x3a3) + " " + chr(0x416) + chr(0x419)
