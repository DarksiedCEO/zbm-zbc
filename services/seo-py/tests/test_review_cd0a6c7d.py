def shown_values(view, values: list) -> int:
    out = json.dumps(view, ensure_ascii=False) + json.dumps(view)
    return sum(1 for v in values if v in out)


def evidence_fields(view) -> list:
    return [(k, row["evidence"][k]) for row in view["result"]["facts"]["rows"] for k in ("excerpt", "title", "hint")
            if row.get("evidence") and row["evidence"].get(k)]


def e2e_labels_summary(tmp_path, seed: int = SEED + 20) -> dict:
    r = random.Random(seed)
    h, forms, values, view = e2e_run(tmp_path, r)
    fields = evidence_fields(view)
    disk = vw.written(h)
    return {"forms": len(forms), "values": len(values), "fields": len(fields),
            "masked": sum(1 for _k, f in fields if f["alert"]), "shown": shown_values(view, values),
            "on_disk": sum(1 for v in values if v in disk),
            "reasons": sorted({f["reason"] for _k, f in fields if f["alert"]}), "mark": vw.MARK in json.dumps(view)}


def test_a_citation_run_carrying_the_forms_is_read_by_its_owner_with_no_value_shown(tmp_path):
    s = e2e_labels_summary(tmp_path)
    print(f"end to end, labels: {s}")
    assert s["forms"] == 27 and s["values"] == 81
    assert s["shown"] == 0 and s["on_disk"] == 0
    assert s["fields"] >= 81 and s["masked"] == s["fields"] and s["reasons"] == ["LOOKS_LIKE_CREDENTIAL"]
    assert s["mark"]                                           # the owner does read the run: a legitimate URL in full


class PageFetcher:
    """Every URL answers a page (200, HTML); the URLs asked for are recorded."""

    def __init__(self):
        self.fetched = []

    def fetch(self, url, robots_cache=None, guard=None, **kw):
        self.fetched.append(url)
        guard(capability="fetch", provider="web")
        return FetchResult(url=url, state="OK", final_url=url, status=200, content_type="text/html",
                           body=b"<html><head><title>page</title></head><body>ok</body></html>")


def e2e_ordinary_urls() -> list:
    """Own-site URLs whose path holds the Japanese loanword and the Hindi phrase (a slug), and two plain ones."""
    return [f"https://site.test/blog/{LOANWORD}", "https://site.test/hi/" + "-".join(HINDI_PHRASE) + "-\u0928\u0902\u092c\u0930",
            "https://site.test/guides/orchid-lantern", "https://site.test/guides/heron-notes"]


def e2e_ordinary_summary(tmp_path) -> dict:
    """A citation run with URL resolution ON, citing ``e2e_ordinary_urls``: what was fetched, how each cited URL
    was classified, and whether the owner reads the titles, hints and excerpts in full."""
    urls = e2e_ordinary_urls()
    phrase = " ".join(HINDI_PHRASE)
    a = ProviderAnswer("ANSWER", f"Z Best Media explains the {LOANWORD} and the {phrase} office.", urls, "m", "1",
                       cite_from_text=False, provider="openai", asked_at="2026-10-09T18:00:00Z")
    a.citation_titles = {urls[0]: f"{LOANWORD}: the guide", urls[1]: f"{phrase}: map"}
    a.citation_hints = {urls[0]: f"{LOANWORD} is explained here", urls[1]: f"{phrase} is near"}
    h = vw.harness(tmp_path, SEO_CALLUM_RESOLVE_URLS="1")
    fetcher = PageFetcher()
    h.ports.engines["openai"] = vw.Port([a])
    h.ports.fetcher = fetcher
    h.ok(h.post("/tenants/zbm/domains", {"request_id": rid(), "domains": [vw.DOMAIN]}, andre=True))
    psid = h.ok(h.post("/tenants/zbm/prompt-sets", {
        "request_id": rid(), "name": "core", "brand_terms": ["Z Best Media"], "competitor_domains": ["competitor.test"],
        "prompts": ["who recovers marketplace revenue"], "engines": ["openai"]}), 201)["prompt_set_id"]
    run = h.ok(h.post("/tenants/zbm/citation-runs", {"request_id": rid(), "domain": vw.DOMAIN,
                                                     "prompt_set_id": psid}), 201)
    view = h.ok(h.get(f"/tenants/zbm/citation-runs/{run['citation_run_id']}", caller="dashboard"))
    rows = view["result"]["facts"]["rows"]
    fields = evidence_fields(view)
    cited = [row["evidence"]["cited_url"] for row in rows if row.get("evidence") and row["evidence"].get("cited_url")]
    return {"status": run["status"], "fetched": sorted(set(urls) & set(fetcher.fetched)), "fetches": len(set(fetcher.fetched)),
            "classes": dict(collections.Counter((row["class"], row.get("reason"), (row.get("chain") or {}).get("resolution"))
                                                for row in rows)),
            "rows": len(rows), "fields": len(fields), "masked": sum(1 for _k, f in fields if f["alert"]),
            "titles": sorted({f["value"] for k, f in fields if k == "title" and not f["alert"]}),
            "urls_shown": sorted({c["value"] for c in cited if not c["alert"]})}


def test_a_citation_run_citing_urls_with_ordinary_japanese_and_hindi_words_fetches_them_all(tmp_path):
    """The review's own measurement: at cd0a6c7d one of these four own-site URLs was fetched; the other three rows
    became INCONCLUSIVE (the cited URL was not fetched) and their titles were masked."""
    s = e2e_ordinary_summary(tmp_path)
    urls = e2e_ordinary_urls()
    print(f"end to end, ordinary URLs: status={s['status']} fetched={len(s['fetched'])} of {len(urls)} "
          f"classes={s['classes']} fields={s['fields']} masked={s['masked']}")
    assert s["status"] == "completed" and s["fetched"] == sorted(urls) and s["fetches"] == 4
    assert set(s["classes"]) == {("STRENGTH_URL", None, "RESOLVED")} and s["rows"] >= 4
    assert s["masked"] == 0 and s["fields"] >= 3 * s["rows"] // 2
    assert s["titles"] == sorted([f"{LOANWORD}: the guide", " ".join(HINDI_PHRASE) + ": map"])
    assert s["urls_shown"] == sorted(urls)


