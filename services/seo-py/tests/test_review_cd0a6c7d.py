def import_copy(tmp_path, edit) -> subprocess.CompletedProcess:
    """A copy of the module with its source edited, imported by a fresh interpreter."""
    src = pathlib.Path(sg.__file__)
    text = edit(src.read_text(encoding="utf-8"))
    copy = tmp_path / "secret_guard_copy.py"
    copy.write_text(text, encoding="utf-8")
    code = ("import importlib.util, sys\n"
            f"sys.path.insert(0, {str(src.parent.parent)!r})\n"
            f"spec = importlib.util.spec_from_file_location('secret_guard_copy', {str(copy)!r})\n"
            "m = importlib.util.module_from_spec(spec)\n"
            "spec.loader.exec_module(m)\n"
            "print('imported', len(m._JOINED))\n")
    return subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, timeout=120)


