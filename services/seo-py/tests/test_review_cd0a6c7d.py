def lane_divergence() -> dict:
    """Every code point whose strict-lane Latin normal form is ASCII letters, put in place of those letters in a
    listed label (in the code point's own case) before a separator and a run-time value: the code points for
    which the strict lane flags a label and the client view shows the text, by documented class."""
    r = random.Random(SEED + 9)
    keys = sorted(set(sg._JOINED) | set(sg._PIECES), key=lambda k: (-len(k), k))
    out: dict = collections.defaultdict(list)
    tried = 0
    for o in range(0x80, 0x110000):
        c = chr(o)
        if unicodedata.category(c)[0] in "CMZ":
            continue
        k = sg._label_norm(c)
        if not (k and k.isascii() and k.isalpha()):
            continue
        word = next((w for w in keys if k in w), None)
        if word is None:
            continue
        tried += 1
        upper = c.lower() != c
        label = (word.upper() if upper else word).replace(k.upper() if upper else k, c, 1)
        t = f"{label}: {value(r)}"
        if not flagged(t) or masked(t):
            continue
        cv, cat = sg._cv_label_view(c), unicodedata.category(c)
        if not cv.isascii() and cat == "Ll" and c.casefold() != c:
            cls = "small_letter_read_by_case_folding_only"
        elif cv.isascii() and len(k) == 2 and cat in ("Ll", "Lt") and "GRAMMENI" in unicodedata.name(c):
            cls = "greek_eta_with_iota_subscript"
        elif cv.isascii() and len(k) == 2 and cat == "Lu" and cv.lower() != k:
            cls = "capital_read_as_two_other_letters"
        elif cv.isascii() and len(k) == 1 and cat == "Lu" and cv == "I" and k == "l":
            cls = "capital_lookalike_of_i_and_l"
        elif cv.isascii() and len(k) == 1 and cat == "Lu" and cv.lower() != k:
            cls = "capital_whose_lookalike_is_another_letter"
        else:
            cls = "UNDOCUMENTED"
        out[cls].append(o)
    out["tried"] = tried
    return out


def test_the_lane_divergence_is_pinned_to_its_documented_classes():
    """Review SHOULD S2 (ADR 0051 decision 72). The strict lane reads a letter through case folding and the
    ``lookalikes`` table; the client view reads it through its own cased table. They differ for the homoglyph
    classes below (the strict lane flags, the client view shows): documented, NOT closed in this round. A code
    point outside those classes fails this test; the sharp s, which was one, is gone."""
    d = lane_divergence()
    counts = {k: len(v) for k, v in d.items() if k != "tried"}
    print(f"lane divergence: code points tried={d['tried']} divergent={sum(counts.values())} by class={counts}")
    assert d["tried"] == 2711
    assert "UNDOCUMENTED" not in counts, [hex(o) for o in d["UNDOCUMENTED"]][:20]
    assert counts == {"capital_whose_lookalike_is_another_letter": 50, "capital_lookalike_of_i_and_l": 12,
                      "greek_eta_with_iota_subscript": 21, "capital_read_as_two_other_letters": 1,
                      "small_letter_read_by_case_folding_only": 31}
    every = {o for k, v in d.items() if k != "tried" for o in v}
    assert len(every) == 115 and 0xdf not in every and 0x1e9e not in every
    scripts = collections.Counter(unicodedata.name(chr(o)).split(" ")[0] for o in every)
    assert scripts == {"GREEK": 50, "MATHEMATICAL": 25, "CHEROKEE": 25, "CYRILLIC": 9, "WARANG": 3, "COPTIC": 2, "DESERET": 1}


